#!/usr/bin/env python3
"""Generates the Daylight (light) look overrides in ui/styles.css from the dark rules (2.6).
Every rule whose background is a dark hex colour gets a light twin under body[data-look="daylight"]; `color:#fff` becomes the theme text colour.
Space scenes (stage, HUD, cockpit, home) stay dark on purpose.   python3 scripts/gen-daylight.py"""
import re, colorsys, pathlib
p = pathlib.Path(__file__).resolve().parent.parent / 'ui' / 'styles.css'
css = p.read_text()
BEGIN, END = '/* >>> daylight (generated by scripts/gen-daylight.py) */', '/* <<< daylight */'
if BEGIN in css: css = css[:css.index(BEGIN)].rstrip() + '\n'
SKIP = ('.stage', '.hud', '.cockpit', '.callout', '.camera', '.ck-', '.fd-', '.view-tools', '.vt-', '.gl-', '.launch', '.holo', '#starfield', 'home', '.hero', '.decor', '#decor', '.rock', '.tour', '.boot', 'body[data', '.sky', ':root', '@', '.toast', '.chart')
def light(hexs):
    h = hexs.lstrip('#')
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    if l > 0.3: return None
    l2 = 0.93 - 0.35 * l
    r, g, b = colorsys.hls_to_rgb(hh, l2, min(1, s * 0.9))
    return '#%02x%02x%02x' % (round(r * 255), round(g * 255), round(b * 255))
out = []
for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', css):
    sel, body = m.group(1).strip(), m.group(2)
    if any(k in sel for k in SKIP) or not sel: continue
    decl = []
    bgnew = False
    def sub_color(mo):
        tok = mo.group(0)
        if tok.startswith('#'):
            return light(tok) or tok
        r, g, b = [int(float(x)) for x in mo.group(1, 2, 3)]
        l = light('#%02x%02x%02x' % (r, g, b))
        if not l: return tok
        return 'rgba(%d, %d, %d, %s)' % (int(l[1:3], 16), int(l[3:5], 16), int(l[5:7], 16), mo.group(4) or '1')
    COL = re.compile(r'#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+))?\s*\)')
    for d in re.finditer(r'(background(?:-color|-image)?)\s*:\s*([^;}]+)', body):
        v = d.group(2)
        nv = COL.sub(sub_color, v)
        if nv != v: decl.append(f'{d.group(1)}: {nv}'); bgnew = True
    for d in re.finditer(r'(border(?:-[a-z]+)?-color)\s*:\s*(#[0-9a-fA-F]{6})', body):
        nl = light(d.group(2))
        if nl: decl.append(f'{d.group(1)}: {nl}')
    if re.search(r'(?<![-a-z])color\s*:\s*#fff(?:fff)?\s*(;|$)', body) and (bgnew or 'background' not in body) and not re.search(r'primary|badge|status|conf-|btn\.good|\.active|\.on\b|\.ok\b|\.bad\b|sel', sel):
        decl.append('color: var(--text)')
    if decl:
        sels = ', '.join('body[data-look="daylight"] ' + s.strip() for s in sel.split(','))
        out.append(f'{sels} {{ {"; ".join(decl)}; }}')
css += '\n' + BEGIN + '\n' + '\n'.join(out) + '\n' + END + '\n'
p.write_text(css)
print(len(out), 'daylight rules')
