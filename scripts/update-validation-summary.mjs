// Writes data/validation-summary.js: one line per validated vehicle (rows within band, the worst miss). The assurance report prints it
// without re-flying nine rockets. Re-run after any physics or validation-data change:  node scripts/update-validation-summary.mjs
import { writeFileSync } from 'node:fs';
import { VALIDATION_VEHICLES, runValidationFlight, summariseRows } from '../src/core/validation.js';
const out = [];
for (const V of VALIDATION_VEHICLES) {
  const r = runValidationFlight(V.id, { quick: true }), s = summariseRows(r.rows);
  const graded = r.rows.filter((x) => x.kind === 'graded' && x.err != null);
  const worst = graded.sort((a, b) => Math.abs(b.err / (b.tol || 1)) - Math.abs(a.err / (a.tol || 1)))[0];
  out.push({ id: V.id, name: V.name, status: r.sim.result.status, pass: s.pass, total: s.total, worst: worst ? { label: worst.label, err: +(worst.err * 100).toFixed(1) } : null });
  console.log(V.id, `${s.pass}/${s.total}`, r.sim.result.status);
}
writeFileSync(new URL('../data/validation-summary.js', import.meta.url), `// Generated by scripts/update-validation-summary.mjs (${new Date().toISOString().slice(0, 10)}). Do not edit by hand.\nexport const VALIDATION_SUMMARY = ${JSON.stringify(out, null, 2)};\n`);
